## 9. Manual Profile Review Checklist

Before any DM, classify the profile.

### Green flags (Buyer signals)
- founder-led business
- paid offer is visible
- paying clients or clear proof of delivery
- language about growth friction / complexity / messaging / capacity
- no AI framework selling
- no prompt bait front-end
- implementation pain is visible

### Yellow flags (Manual review needed)
- coach
- educator
- consultant with broad wording
- “systems” language but unclear offer
- strong audience but unclear business model

### Red flags (Do not buyer-outbound)
- AI operating system seller
- prompt library seller
- automation educator
- “comment X and I’ll send the prompts”
- heavy freebie funnel
- “build your own AI team” positioning
- direct category overlap

