## 10. DM Logic by Category

## Buyer
### Objective
Start a real conversation around bottlenecks.

### DM style
- short
- warm
- problem-aware
- one question max

### Example direction
“Hey [Name] — your positioning around [X] stands out. I work with founder-led premium service businesses that have real expertise but messy revenue architecture behind the scenes. Curious — is growth more constrained for you right now by lead flow, delivery complexity, or message consistency?”

---

## Peer
### Objective
Build relationship, not sell.

### Example direction
“Hey [Name] — I like how you’re thinking about [X]. Feels adjacent to some of the work I’m building around founder-led revenue systems. Wanted to connect.”

---

## Partner
### Objective
Open a strategic relationship lane.

### Example direction
“Hey [Name] — your audience / angle around [X] looks unusually aligned with the kind of founder-led businesses I’m building around. Thought it made sense to connect.”

---

## Competitor
### Objective
Usually none.

### Rule
Do not use standard outbound.
Only engage if there is a clear strategic reason:
- relationship diplomacy
- category observation
- potential future collaboration
- intelligence

---

## 11. What Must Never Be Said in First Outreach

Do not say:
- “I help everyone scale with AI”
- “I built an AI operating system”
- “I can automate your business”
- “Can I show you my framework?”
- “Book a call”
- “Free consultation”
- “DM me SYSTEM”
- anything that sounds like a prompt seller or growth hack account

Do not overuse:
- ecosystem
- friction
- acquisition model
- leverage
- optimize
- high-touch onboarding
- strategic alignment

### Canonical tone
Warm founder
Sharp but human
Curious without interrogating
Commercially aware but not pitchy

