## 14. Hard Decision

AGS should **not** broadly target people who:
- already teach the market how to build AI systems,
- sell prompt libraries,
- sell operating systems,
- monetize the same mechanism category,
- or are more likely to reverse-engineer AGS than buy it.

These people should be:
- excluded,
- deprioritized,
- or moved into Peer / Competitor / Partner categories.

They are not the core buyer class.

