## 6. Classification Framework

## A. Buyer
### Who belongs here
- founder-led premium service business
- real offer
- real clients
- real operational friction
- not selling AI system education
- wants implementation

### Signals
- language about bottlenecks
- language about inconsistency / scale / complexity
- real authority + real friction
- not obviously category-adjacent

### Treatment
- outbound: YES
- application funnel: YES
- diagnostic path: YES

---

## B. Peer
### Who belongs here
- adjacent strategic thinker
- category-adjacent operator
- likely useful relationship
- low likelihood of buying
- moderate likelihood of mutual value

### Signals
- sophisticated thinking
- overlaps with AGS themes
- may sell consulting / growth / ops
- not necessarily direct competitor
- probably not implementation buyer

### Treatment
- outbound as buyer: NO
- relationship outreach: YES
- application funnel: usually NO
- possible roundtable / referral / collaboration lane

---

## C. Competitor
### Who belongs here
- publicly sells AI systems / AI OS / prompts / frameworks
- targets the same buyer class with similar mechanism language
- teaches or monetizes adjacent implementation logic

### Signals
- “AI Operating System”
- “build your own AI sales team”
- “prompt library”
- “AI OS for coaches”
- “done-for-you AI systems for experts”
- content centered on system-building mechanics to your exact buyer category

### Treatment
- outbound as buyer: NO
- application funnel: NO
- monitor: YES
- competitor intelligence: YES
- relationship only if strategic, never confused with prospecting

---

## D. Partner
### Who belongs here
- has trusted access to AGS buyer class
- may not need AGS themselves
- can introduce, distribute, host, or elevate

### Signals
- audience trust
- niche relevance
- adjacent but non-overlapping offer
- community role
- host / connector / strategic node

### Treatment
- relationship outreach: YES
- buyer funnel: NO
- partner lane: YES

---

## 7. STK-Type Profile Rule

### Pattern
A founder who publicly teaches an AI operating system / AI infrastructure / AI framework to their own niche and appears to sell similar logic to expert businesses.

### Default classification
**Peer → Competitor-adjacent**

### Possible alternative classification
**Partner**, but only with clear non-overlap and mutual value.

### Not to be treated as
- standard prospect
- normal outbound buyer
- default application-funnel candidate

### Why
Because such a profile is more likely to:
- understand the mechanism category,
- compare or absorb your logic,
- teach their own audience,
- create category blur,
- consume insight without converting.

