## Purpose
This document turns the current AGS ICP boundary conclusions into one operational doctrine for:
- prospecting,
- manual lead classification,
- LinkedIn targeting,
- DM opening logic,
- separation between buyers, peers, competitors, and partners.

It exists to stop AGS from wasting time on category-neighbors, framework sellers, AI educators, DIY operators, and wrong-fit leads.

---

## 1. Executive Judgment

AGS does **not** have a core ICP problem.

AGS has a **positioning-boundary problem**.

The core ICP is broadly correct:
- founder-led,
- premium service,
- real expertise,
- real offer,
- real operational friction,
- implementation-ready.

The issue is that the front-end and prospecting layer can still be too porous around:
- AI-adjacent coaches,
- AI operating system sellers,
- prompt-library sellers,
- framework educators,
- DIY builders,
- adjacent strategists.

### Canonical decision
- Keep the core ICP.
- Tighten exclusion logic.
- Split people operationally into:
  - Buyer
  - Peer
  - Competitor
  - Partner
- Stop treating “smart expert founder” as automatically equal to “qualified buyer.”

---

## 2. Core ICP

### Core ICP
Founder-led premium service businesses that:
- already sell real expertise,
- are not in the business of teaching AI systems,
- have paying clients,
- have operational friction,
- have authority / positioning / message / follow-up inconsistency,
- value founder voice,
- want implementation, not education,
- are willing to pay for diagnosis before build.

### Typical examples
- consultants
- agencies
- boutique expert firms
- fractional operators
- service-led founders
- premium advisors
- expert-led businesses with active delivery complexity

### Core buying signals
- talks about bottlenecks, not frameworks
- talks about growth friction, not “give me prompts”
- has real business context
- has real clients
- wants implementation support, not AI education
- does not publicly position themselves as an AI-system teacher

---

## 3. Secondary ICP

### Secondary ICP
Possible buyers, but need stronger review:
- selected coaches
- selected educators
- solo experts moving into structured business growth
- expert founders with traction but less operational maturity

### Conditions
Include only if they:
- have a real paid offer,
- have real clients,
- are not monetizing AI systems as their own category,
- are not clearly framework sellers,
- show implementation pain rather than “teach me the system” behavior.

### Rule
Secondary ICP can be prospected, but only after manual screening.

---

## 4. Exclusion ICP

### Do not target as normal buyers
- AI operating system sellers
- prompt-library sellers
- “build your own AI team” educators
- AI implementation coaches
- automation consultants selling similar enablement
- framework creators monetizing adjacent logic
- freebie hunters
- no-offer businesses
- beginners seeking templates
- people asking for prompts before they can describe a business bottleneck
- anyone likely to study and copy rather than buy

### Canonical rule
These profiles do **not** enter the normal AGS buyer funnel.

---

## 5. Partnership ICP

### Partnership ICP
People and entities who may not be buyers, but may become:
- distribution nodes,
- referral sources,
- authority bridges,
- collaboration partners,
- future roundtable candidates.

### Typical examples
- podcasters
- community builders
- founders with trusted niche audiences
- adjacent consultants who serve the AGS buyer class
- educators with buyer access but non-overlapping offers
- peer operators with strong audience trust

### Rule
Partnership ICP gets relationship-led outreach, not buyer-led outreach.

